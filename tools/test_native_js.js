// يتحقق من مقاطع JS التي تستدعيها الواجهة الأصلية (AppShell) على المنصة الأصلية.
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const dart = fs.readFileSync(path.join(root, 'lib/web_shell.dart'), 'utf8');
const CHROME = dart.match(/_chromeScript = r'''([\s\S]*?)''';/)[1];
const SHIM = fs.readFileSync(path.join(root, 'assets/web/native_shim.js'), 'utf8');
let pass = 0, fail = 0;
const check = (n, c, x = '') => { c ? pass++ : fail++; console.log((c ? 'PASS ' : 'FAIL ') + n + (c ? '' : ' ' + x)); };
(async () => {
  const b = await chromium.launch();
  const page = await (await b.newContext({ viewport: { width: 412, height: 915 } })).newPage();
  const errs = []; page.on('pageerror', e => errs.push(String(e)));
  await page.addInitScript(() => { window.Exam6Channel = { postMessage: () => {} }; });
  await page.goto('file://' + path.join(root, 'assets/web/index.html'));
  await page.evaluate(CHROME);
  await page.evaluate(SHIM);
  check('هيدر الويب مخفي', await page.evaluate(() => getComputedStyle(document.querySelector('header.app-header')).display === 'none'));
  check('الشريط السفلي للويب مخفي', await page.evaluate(() => getComputedStyle(document.querySelector('nav.mobile-bottom-nav')).display === 'none'));
  check('نافذة الترحيب مغلقة', await page.evaluate(() => !document.getElementById('welcome-modal').classList.contains('open')));
  const stats = JSON.parse(await page.evaluate("(function(){try{syncMeta();}catch(e){}var e=currentExam;return JSON.stringify({q:e.questions.length,s:e.questions.reduce(function(a,b){return a+(parseFloat(b.score)||0)},0),t:parseFloat(e.meta.maxScore)||0,title:e.meta.title||'',subject:e.meta.subject||'',grade:e.meta.grade||''});})()"));
  check('JS الإحصاءات يعيد أرقاماً', typeof stats.q === 'number' && typeof stats.s === 'number' && typeof stats.t === 'number', JSON.stringify(stats));
  await page.evaluate(() => { navigateTo('editor'); document.getElementById('meta-title').value = 'اختبار س'; syncMeta(); saveCurrentExam(); });
  await page.waitForTimeout(500);
  const id = await page.evaluate(async () => (await dbGetAllExams())[0].id);
  await page.evaluate(() => { currentExam.meta.title = 'تغيّر'; });
  await page.evaluate("currentExam=getDefaultExamState();populateEditorFromState();applyDesignVariables();renderLivePreview();");
  check('اختبار جديد يفرّغ الحالة', await page.evaluate(() => currentExam.meta.title !== 'اختبار س'));
  await page.evaluate(`loadSavedExam('${id}')`);
  await page.waitForTimeout(500);
  check('فتح اختبار محفوظ يحمّله', await page.evaluate(() => currentExam.meta.title === 'اختبار س'));
  await page.evaluate('openBulkPasteModal()');
  const hasModal = await page.evaluate(() => !!document.querySelector('.modal-backdrop.open'));
  check('اللصق الجماعي يفتح نافذة', hasModal);
  const closed = JSON.parse(await page.evaluate("(function(){var m=document.querySelector('.modal-backdrop.open');if(m){closeModal(m.id);return JSON.stringify({m:1});}return JSON.stringify({m:0});})()"));
  check('زر الرجوع يغلق النافذة المفتوحة', closed.m === 1 && !(await page.evaluate(() => !!document.querySelector('.modal-backdrop.open'))));
  await page.evaluate(`dbDeleteExam('${id}')`);
  await page.waitForTimeout(300);
  check('حذف عبر dbDeleteExam', (await page.evaluate(async () => (await dbGetAllExams()).length)) === 0);
  check('لا أخطاء JS', errs.length === 0, errs.join('|'));
  await b.close();
  console.log(`\nالنتيجة: ${pass} نجاح، ${fail} فشل`);
})();
